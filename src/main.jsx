import React from 'react';
import ReactDOM from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import App from './App.jsx';
import { ThemeProvider } from './contexts/ThemeContext';
import { attachScrollTracking } from './lib/scrollIdle';
import './index.css';

// Let canvas effects skip their frames while the user is scrolling.
attachScrollTracking();

// Prevent canvas elements (like Spline or Three.js) from stealing scroll focus
if (typeof window !== 'undefined' && window.HTMLCanvasElement) {
  const originalFocus = window.HTMLCanvasElement.prototype.focus;
  window.HTMLCanvasElement.prototype.focus = function (options) {
    originalFocus.call(this, { ...options, preventScroll: true });
  };
}

class ErrorBoundary extends React.Component {
  constructor(props) {
    super(props);
    this.state = { hasError: false, error: null };
  }
  static getDerivedStateFromError(error) {
    return { hasError: true, error };
  }
  componentDidCatch(error, errorInfo) {
    console.error("ErrorBoundary caught an error", error, errorInfo);
  }
  render() {
    if (this.state.hasError) {
      return (
        <div style={{ padding: 20, color: 'red', background: 'white', zIndex: 9999, position: 'absolute' }}>
          <h1>Something went wrong.</h1>
          <pre>{this.state.error?.toString()}</pre>
        </div>
      );
    }
    return this.props.children;
  }
}

ReactDOM.createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <ErrorBoundary>
      <BrowserRouter>
        <ThemeProvider>
          <App />
        </ThemeProvider>
      </BrowserRouter>
    </ErrorBoundary>
  </React.StrictMode>,
);
